function getAlmanacTerm(key, currentValue) {
  const normalizedKey = ALIASES[key] || key;
  const term = TERMS[normalizedKey];
  if (!term) return null;
  return Object.assign({
    key: normalizedKey,
    currentValue: Array.isArray(currentValue) ? currentValue.join("、") : currentValue || ""
  }, term);
}

